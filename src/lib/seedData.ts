function addDaysAndHours(days: number, hours: number, minute = 0): string {
  const now = new Date();
  const target = new Date(
    now.getFullYear(),
    now.getMonth(),
    now.getDate() + days,
    hours,
    minute,
    0
  );
  return target.toISOString();
}

